class Product:
    def __init__(self, product_id, name, price, quantity):
        self.product_id = product_id
        self.name = name
        self.price = price
        self.quantity = quantity


class Store:
    def __init__(self):
        self.products = []
        self.total_sales = 0

    def add_product(self):
        product_id = input("ID: ")
        name = input("Mahsulot nomi: ")
        price = float(input("Narxi: "))
        quantity = int(input("Soni: "))

        product = Product(product_id, name, price, quantity)
        self.products.append(product)

        print("✅ Mahsulot qo'shildi.")

    def show_products(self):
        if len(self.products) == 0:
            print("Mahsulot mavjud emas.")
            return

        print("\n===== MAHSULOTLAR =====")

        for product in self.products:
            print(f"""
ID: {product.product_id}
Nomi: {product.name}
Narxi: {product.price}
Soni: {product.quantity}
------------------------
""")

    def buy_product(self):
        product_id = input("Sotib olinadigan mahsulot ID sini kiriting: ")

        for product in self.products:
            if product.product_id == product_id:

                if product.quantity == 0:
                    print("Mahsulot tugagan.")
                    return

                quantity = int(input("Nechta olasiz: "))

                if quantity > product.quantity:
                    print("Yetarli mahsulot yo'q.")
                    return

                total = quantity * product.price

                product.quantity -= quantity

                self.total_sales += total

                print(f"""
Xarid muvaffaqiyatli!

Jami narx: {total} so'm
""")
                return

        print("Mahsulot topilmadi.")

    def sales(self):
        print(f"\nJami savdo: {self.total_sales} so'm")


