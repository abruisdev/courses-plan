import json


class Student:
    def __init__(self, student_id, first_name, last_name, age, course, average):
        self.student_id = student_id
        self.first_name = first_name
        self.last_name = last_name
        self.age = age
        self.course = course
        self.average = average

    def to_dict(self):
        return {
            "id": self.student_id,
            "first_name": self.first_name,
            "last_name": self.last_name,
            "age": self.age,
            "course": self.course,
            "average": self.average
        }


